-- 19. JOIN + WHERE

SELECT CLIENTE.nome, JOGO.titulo,
       LOCACAO.status
FROM LOCACAO
INNER JOIN CLIENTE
ON LOCACAO.id_cliente = CLIENTE.id_cliente
INNER JOIN JOGO
ON LOCACAO.id_jogo = JOGO.id_jogo
WHERE LOCACAO.status = 'ABERTA';

-- 20. GROUP BY

SELECT CLIENTE.nome,
       COUNT(LOCACAO.id_locacao) AS total_locacoes
FROM CLIENTE
INNER JOIN LOCACAO
ON CLIENTE.id_cliente = LOCACAO.id_cliente
GROUP BY CLIENTE.id_cliente, CLIENTE.nome
ORDER BY total_locacoes DESC;

-- 21. LEFT JOIN

SELECT CLIENTE.nome,
       COUNT(LOCACAO.id_locacao) AS total_locacoes
FROM CLIENTE
LEFT JOIN LOCACAO
ON CLIENTE.id_cliente = LOCACAO.id_cliente
GROUP BY CLIENTE.id_cliente, CLIENTE.nome
ORDER BY total_locacoes DESC;

